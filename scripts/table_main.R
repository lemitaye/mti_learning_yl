# Table 2: reconstruct the manuscript's employment models and add IV diagnostics.
# Run from the project root: Rscript scripts/table_main.R [output_table.tex]
# Default output is staged; review it before copying into the manuscript.
# Uses the same covariates, filters, and conventional SEs as estimation.R.
# Method references:
# https://stat.ethz.ch/CRAN/web/packages/AER/AER.pdf
# https://economics.mit.edu/sites/default/files/2023-06/wirev_092218-_corrected_0.pdf
local({
  args <- commandArgs(trailingOnly = TRUE)
  out_file <- if (length(args)) args[[1]] else 'output/tables/tableII_mod.tex'
  dir.create(dirname(out_file), recursive = TRUE, showWarnings = FALSE)
  dat <- readr::read_csv('data/non_aa_samp.csv', show_col_types = FALSE)
  dat[] <- lapply(dat, function(x) if (is.character(x)) factor(x) else x)
  dat <- dat[!is.na(dat$raw_lang) & dat$raw_lang != 0, ]
  controls <- paste(
    'chsex + zbfa + stunting + caredu_r1 + careage_r1 + factor(caresex_r1)',
    '+ hhsize + wi_new + hq_new + cd_new + elecq_new + ownlandhse_r1',
    '+ factor(foodsec_r3)'
  )
  outcomes <- rep(c('wage_employII', 'wage_employ'), 2)
  results <- lapply(seq_along(outcomes), function(i) {
    y <- outcomes[[i]]
    sample <- if (i > 2) dat[dat$region != 'Amhara', ] else dat
    # Fix the complete-case sample BEFORE fitting either stage or diagnostics.
    variables <- all.vars(as.formula(paste(y, '~ IMTI + E_is +', controls)))
    sample <- sample[complete.cases(sample[, variables]), ]
    iv <- lfe::felm(as.formula(paste(y, '~', controls, '| 0 | (IMTI ~ E_is)')),
                    data = sample)
    fs <- lm(as.formula(paste('IMTI ~ E_is +', controls)), data = sample)
    restricted <- lm(as.formula(paste('IMTI ~', controls)), data = sample)
    # With one excluded instrument, its partial F is the squared t statistic.
    # This is NOT the overall first-stage F on all regressors.
    fs_row <- summary(fs)$coefficients['E_is', ]
    f_stat <- unname(fs_row['t value']^2)
    # Scalar FWL sandwich equals vcovHC(fs, type='HC1')['E_is','E_is'].
    # Avoid inverting a full robust covariance with singleton nuisance dummies.
    z_resid <- residuals(lm(as.formula(paste('E_is ~', controls)), data = sample))
    hc1_var <- nobs(fs) / df.residual(fs) *
      sum((z_resid * residuals(fs))^2) / sum(z_resid^2)^2
    f_hc1 <- unname(coef(fs)['E_is']^2 / hc1_var)
    partial_r2 <- 1 - sum(residuals(fs)^2) / sum(residuals(restricted)^2)
    # Anderson-Rubin H0: beta_MTI = 0: regress y - 0*IMTI on X and E_is.
    # The conventional F test is weak-IV robust under the iid normal model;
    # it does not allow arbitrary region-level dependence.
    ar <- lm(as.formula(paste(y, '~ E_is +', controls)), data = sample)
    ar_f <- unname(summary(ar)$coefficients['E_is', 't value']^2)
    ar_hc1_var <- nobs(ar) / df.residual(ar) *
      sum((z_resid * residuals(ar))^2) / sum(z_resid^2)^2
    ar_hc1_wald <- unname(coef(ar)['E_is']^2 / ar_hc1_var)
    iv_row <- tail(summary(iv)$coefficients, 1)[1, ]
    # Check that the diagnostic first stage matches felm's actual first stage.
    stopifnot(iv$N == nobs(fs),
              isTRUE(all.equal(unname(fs_row[1:2]),
                unname(summary(iv$stage1)$coefficients['E_is', 1:2]), tolerance = 1e-9)))
    data.frame(column = i, outcome = y, excluding_Amhara = i > 2,
      n = nobs(fs), first_stage_df = df.residual(fs),
      iv_beta = iv_row[1], iv_se = iv_row[2], iv_p = iv_row[4],
      first_stage_beta = fs_row[1], first_stage_se = fs_row[2],
      first_stage_p = fs_row[4], first_stage_F = f_stat,
      first_stage_F_HC1 = f_hc1, partial_R2 = partial_r2,
      AR_F_beta0 = ar_f,
      AR_p_beta0 = pf(ar_f, 1, df.residual(ar), lower.tail = FALSE),
      AR_Wald_HC1_beta0 = ar_hc1_wald,
      AR_p_HC1_beta0 = pchisq(ar_hc1_wald, 1, lower.tail = FALSE),
      row.names = NULL)
  })
  stats <- do.call(rbind, results)
  fmt <- function(x, digits = 3) formatC(x, format = 'f', digits = digits)
  stars <- function(p) ifelse(p < .01, '$^{***}$',
                             ifelse(p < .05, '$^{**}$', ifelse(p < .1, '$^{*}$', '')))
  row <- function(label, values) paste0(label, ' & ', paste(values, collapse = ' & '), ' \\\\')
  panel <- function(label) paste0('\\multicolumn{5}{l}{\\textbf{', label, '}} \\\\')
  L <- c(
    '% Generated by scripts/table_main.R; no manual numerical edits.',
    '\\begin{table}[!htbp] \\centering',
    '\\caption{Main results} \\label{tab:mainreg}',
    '\\begin{threeparttable}', '\\small',
    '\\begin{tabular}{@{\\extracolsep{5pt}}lcccc}', '\\hline\\hline',
    ' & \\multicolumn{2}{c}{\\textbf{Whole Sample}} & \\multicolumn{2}{c}{\\textbf{Excluding Amhara}} \\\\',
    '\\cline{2-3} \\cline{4-5}',
    ' & Salary & Wage & Salary & Wage \\\\',
    ' & Employed & Employed & Employed & Employed \\\\',
    ' & (1) & (2) & (3) & (4) \\\\', '\\hline',
    panel('Panel A: 2SLS'),
    row('$MTIuse$', paste0(fmt(stats$iv_beta), stars(stats$iv_p))),
    row('', paste0('(', fmt(stats$iv_se), ')')), '\\hline',
    panel('Panel B: First stage'),
    row('$E_{is}$', paste0(fmt(stats$first_stage_beta), stars(stats$first_stage_p))),
    row('', paste0('(', fmt(stats$first_stage_se), ')')),
    row('Excluded-instrument $F$', fmt(stats$first_stage_F, 2)),
    row('$p$-value ($E_{is}=0$)', ifelse(stats$first_stage_p < .001, '$<0.001$', fmt(stats$first_stage_p))),
    row('Partial $R^2$', fmt(stats$partial_R2)),
    row('First-stage $F$ (HC1)', fmt(stats$first_stage_F_HC1, 2)),
    row('Residual degrees of freedom', as.character(stats$first_stage_df)), '\\hline',
    panel('Panel C: Weak-instrument-robust inference'),
    row('Anderson--Rubin $F$', fmt(stats$AR_F_beta0, 2)),
    row('Anderson--Rubin $p$-value', fmt(stats$AR_p_beta0)),
    row('Anderson--Rubin $p$ (HC1)', fmt(stats$AR_p_HC1_beta0)), '\\hline',
    row('Observations', as.character(stats$n)), '\\hline\\hline',
    '\\end{tabular}', '\\begin{tablenotes} \\footnotesize',
    paste0('\\item \\textit{Notes:} Controls are child sex, BMI-for-age z-score, stunting, ',
      'caregiver education, age and sex, household size, wealth, housing-quality and ',
      'consumer-durables indices, electricity, land ownership, and food-security categories. ',
      'Each first stage uses the exact corresponding second-stage sample.'),
    paste0('\\item The excluded-instrument $F$ tests $E_{is}=0$ conditional on all controls ',
      '(one numerator degree of freedom); its conventional standard error matches Panel B. ',
      'Partial $R^2$ measures the additional variation in MTI intake explained by $E_{is}$. ',
      'HC1 uses heteroskedasticity-robust first-stage variance with a degrees-of-freedom correction.'),
    paste0('\\item Anderson--Rubin tests $H_0:\\beta_{MTI}=0$ using a conventional $F$ test ',
      'of $E_{is}$ in the reduced form, retaining validity under weak identification under ',
      'the iid normal model; the HC1 $p$-value uses an asymptotic $\\chi^2_1$ reference ',
      'allowing heteroskedasticity. These test the employment effect, not instrument strength. ',
      'These diagnostics do not address dependence within the four regional policy clusters. ',
      'There is one excluded instrument and one endogenous regressor, so an overidentification test is unavailable.'),
    '\\item Conventional standard errors are in parentheses. *** Significant at 1\\%, ** at 5\\%, * at 10\\%.',
    '\\end{tablenotes}', '\\end{threeparttable}', '\\end{table}'
  )
  writeLines(L, out_file)
  diagnostics_file <- sub('\\.tex$', '_diagnostics.csv', out_file)
  if (identical(diagnostics_file, out_file)) diagnostics_file <- paste0(out_file, '_diagnostics.csv')
  write.csv(stats, diagnostics_file, row.names = FALSE)
  print(stats[, c('column', 'n', 'first_stage_F', 'first_stage_F_HC1', 'partial_R2', 'AR_p_beta0')])
  message('Wrote ', out_file, ' and ', diagnostics_file)
})
