# Each R4 test belongs to a participant, even if employment is observed twice.
# Use historical household resources to avoid conditioning on R7 resources.
learning <- sample |>
  arrange(round) |>
  distinct(child_id, .keep_all = TRUE) |>
  select(-hhsize, -wi_new) |>
  left_join(history, by = "child_id", relationship = "many-to-one") |>
  drop_na(hhsize, wi_new) |>
  group_by(addis = region == "Addis Ababa", yc) |>
  mutate(
    maths = as.numeric(scale(raw_maths_r4)),
    language = as.numeric(scale(na_if(raw_lang_r4, 0))),
    exposure_product = E_is * IMTI
  ) |>
  ungroup()

fit <- function(data, outcome, predictor, employment = FALSE, iv = FALSE,
                additional = character()) {
  terms <- c(lean_terms, "cohort_young", additional)
  if (employment) terms <- c(terms, "round7")
  data <- data |> drop_na(all_of(c(outcome, predictor, terms, "E_is")))
  if (iv) {
    model <- lfe::felm(as.formula(paste(
      outcome, "~", paste(terms, collapse = " + "), "| 0 | (IMTI ~ E_is)"
    )), data = data)
    coef <- coef(summary(model))["`IMTI(fit)`", , drop = TRUE]
  } else {
    model <- lm(reformulate(c(predictor, terms), outcome), data = data)
    coef <- coef(summary(model))[predictor, ]
  }
  tibble(beta = unname(coef[1]), se = unname(coef[2]),
         p = unname(coef[4]), n = nrow(data), r2 = summary(model)$r.squared)
}

ending <- strrep(intToUtf8(92), 2)
row <- function(label, values) {
  paste(paste(c(label, values), collapse = " & "), ending)
}
estimate <- function(label, stats) {
  stars <- case_when(stats$p < .01 ~ "$^{***}$", stats$p < .05 ~ "$^{**}$",
                     stats$p < .10 ~ "$^{*}$", TRUE ~ "")
  c(row(label, paste0(sprintf("%.3f", stats$beta), stars)),
    row("", sprintf("(%.3f)", stats$se)))
}
write_table <- function(name, caption, label, headers, rows, notes) {
  file <- file.path("output/tables", paste0(name, ".tex"))
  writeLines(c(
    "% Generated by code/auxiliary/update_pooled_channel_tables.R",
    "\\begin{table}[!htbp]\\centering",
    paste0("\\caption{", caption, "}"),
    paste0("\\label{", label, "}"),
    "\\begin{threeparttable}\\small",
    paste0("\\begin{tabular}{l", strrep("r", length(headers)), "}\\toprule"),
    row("", headers), "\\midrule", rows, "\\bottomrule\\end{tabular}",
    "\\begin{tablenotes}\\footnotesize", paste("\\item", notes),
    "Conventional SEs in parentheses. Stars indicate significance at",
    "1\\%, 5\\%, and 10\\%, respectively.",
    "\\end{tablenotes}\\end{threeparttable}\\end{table}"
  ), file)
  stopifnot(mirror_output(file, "tables"))
}

