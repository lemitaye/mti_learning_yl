addis <- filter(sample, region == "Addis Ababa")
addis_learning <- filter(learning, .data$addis)
outcomes <- c("maths", "language", "salary_employ", "wage_employ")
addis_fit <- function(iv) {
  imap_dfr(outcomes, function(outcome, i) {
    employment <- i > 2
    fit(if (employment) addis else addis_learning, outcome,
        if (iv) "IMTI" else "E_is", employment, iv)
  })
}
rf <- addis_fit(FALSE)
iv <- addis_fit(TRUE)
stopifnot(identical(rf$n, iv$n))
write_table(
  "tableIII", "Estimates for Addis Ababa", "tab:aareg",
  c("Maths Z-score", "Language Z-score", "Salary employed", "Wage employed"),
  c(paste("\\multicolumn{5}{l}{\\textbf{Panel A: Reduced Form}}", ending),
    estimate("$E_{is}$", rf), "\\midrule",
    paste("\\multicolumn{5}{l}{\\textbf{Panel B: 2SLS}}", ending),
    estimate("MTI", iv), row("Observations", iv$n)),
  sample_note
)

regional <- imap_dfr(outcomes[c(1, 2, 4, 3)], function(outcome, i) {
  employment <- i > 2
  data <- (if (employment) sample else learning) |>
    filter(region %in% c("Tigray", "Oromia")) |>
    mutate(Tigray = as.integer(region == "Tigray"))
  if (outcome == "language") {
    data <- filter(data, testlang_lang == chlang,
                   (Tigray == 1 & chlang == "Tigrigna") |
                     (Tigray == 0 & chlang == "Afaan Oromo"))
  }
  fit(data, outcome, "Tigray", employment, additional = "IMTI")
})
write_table(
  "tableV", "Comparing Estimates for Tigray and Oromia", "tab:oromtig",
  c("Maths Z-score", "Language Z-score", "Wage employed", "Salary employed"),
  c(estimate("Tigray", regional), row("Observations", regional$n),
    row("$R^2$", sprintf("%.3f", regional$r2))),
  paste(sample_note, "Language estimates require matching test and home languages.")
)
print(list(channel = channel, addis_rf = rf, addis_iv = iv, regional = regional))
