# Count participant-round observations in the fixed lean sample.
library(tidyverse)
source("code/helpers/fixed_employment_sample.R")
source("code/helpers/export_paths.R")

sample <- fixed_employment_sample()
counts <- with(sample, table(region, cohort, round))
cells <- matrix(
  as.integer(counts), nrow = dim(counts)[1],
  dimnames = list(rownames(counts), NULL)
)
margins <- rbind(cbind(cells, rowSums(cells)), Total = c(colSums(cells), sum(cells)))
stopifnot(sum(cells) == nrow(sample))

row <- function(values) {
  paste(paste(values, collapse = " & "), strrep(intToUtf8(92), 2))
}
format_row <- function(i) {
  n <- margins[i, ]
  row(c(rownames(margins)[i], sprintf("%d (%.1f\\%%)", n, 100 * n / nrow(sample))))
}
headers <- expand_grid(round = dimnames(counts)[[3]], cohort = dimnames(counts)[[2]])
file <- "output/tables/table_lean_sample_crosstab.tex"
writeLines(c(
  "% Generated by code/auxiliary/write_lean_sample_crosstab.R",
  "\\begin{table}[!htbp]\\centering",
  "\\caption{Analysis sample by region, cohort, and round}",
  "\\label{tab:lean-sample-counts}",
  "\\begin{threeparttable}\\small",
  "\\begin{tabular}{lrrrrr}\\toprule",
  row(c("Region", "\\multicolumn{2}{c}{Round 5}",
        "\\multicolumn{2}{c}{Round 7}", "")),
  "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}",
  row(c("", recode(headers$cohort, old = "Older", young = "Younger"), "Total")),
  "\\midrule",
  vapply(seq_len(nrow(cells)), format_row, character(1)),
  "\\midrule", format_row(nrow(margins)), "\\bottomrule\\end{tabular}",
  "\\begin{tablenotes}\\footnotesize",
  "\\item Cells show participant-round counts and percentages of the full",
  "lean sample, including Addis Ababa. The younger cohort contributes",
  "employment observations in Round 7 only.",
  "\\end{tablenotes}\\end{threeparttable}\\end{table}"
), file)
stopifnot(mirror_output(file, "tables"))
print(margins)
