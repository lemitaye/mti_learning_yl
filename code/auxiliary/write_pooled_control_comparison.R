# Format the common-sample control comparison for the revision manuscript.
fmt <- function(x, digits = 3) formatC(x, format = "f", digits = digits)
stars <- function(p) case_when(
  p < .01 ~ "$^{***}$", p < .05 ~ "$^{**}$",
  p < .10 ~ "$^{*}$", TRUE ~ ""
)
row <- function(label, values) {
  paste(paste(c(label, values), collapse = " & "), strrep(intToUtf8(92), 2))
}

panel <- function(outcome, title) {
  s <- filter(stats, .data$outcome == .env$outcome)
  c(
    paste0("\\multicolumn{4}{l}{\\textbf{", title, "}} \\\\"),
    row("$MTIuse$", paste0(fmt(s$beta), stars(s$p))),
    row("", paste0("(", fmt(s$se), ")")),
    row("Wild bootstrap SE", fmt(s$wild_boot_se)),
    row("Wild bootstrap $p$", fmt(s$wild_boot_p)),
    row("Wild AR score $p$", fmt(s$AR_p_sign_beta0)),
    row("Excluded-instrument $F$", fmt(s$first_stage_F, 2)),
    row("Observations", s$n)
  )
}

