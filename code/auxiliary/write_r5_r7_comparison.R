fmt <- function(x, digits = 3) formatC(x, format = "f", digits = digits)
stars <- function(p) {
  case_when(p < .01 ~ "$^{***}$", p < .05 ~ "$^{**}$",
            p < .10 ~ "$^{*}$", TRUE ~ "")
}
ending <- strrep(intToUtf8(92), 2)
row <- function(label, values) paste(paste(c(label, values), collapse = " & "), ending)
span <- function(width, label, align = "c") {
  paste0("\\multicolumn{", width, "}{", align, "}{", label, "}")
}
rule <- function(first, last) paste0("\\cmidrule(lr){", first, "-", last, "}")
estimate <- function(label, beta, se, p) {
  c(row(label, paste0(fmt(beta), stars(p))), row("", paste0("(", fmt(se), ")")))
}

