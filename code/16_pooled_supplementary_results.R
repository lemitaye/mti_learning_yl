sample <- fixed_employment_sample()
legacy_paths <- file.path("data", c("aa_samp.csv", "non_aa_samp.csv", "ylsample_yc.csv"))
legacy <- map_dfr(legacy_paths, function(path) {
  read_csv(path, col_select = c(child_id, testlang_lang, hhsize, wi_new),
           show_col_types = FALSE)
})
history <- read_csv(
  "data/r7/r7_inperson_analysis.csv",
  col_select = c(child_id, testlang_lang_hist, hhsize_hist, wi_new_hist),
  show_col_types = FALSE
) |>
  rename_with(~ str_remove(.x, "_hist$"))
lookup <- bind_rows(legacy, anti_join(history, legacy, by = "child_id"))
stopifnot(!anyDuplicated(lookup$child_id))

# R4 scores occur once per participant. Use R3 resources for these models
# so household controls precede the tests, including for R7-only participants.
cognitive <- sample |>
  arrange(round) |>
  distinct(child_id, .keep_all = TRUE) |>
  select(-hhsize, -wi_new) |>
  left_join(lookup, by = "child_id", relationship = "one-to-one") |>
  drop_na(hhsize, wi_new) |>
  group_by(addis = region == "Addis Ababa") |>
  mutate(
    std_maths = as.numeric(scale(raw_maths_r4)),
    std_lang = as.numeric(scale(raw_lang_r4)),
    inst = E_is * IMTI
  ) |>
  ungroup()

cognitive_terms <- c(lean_terms, "cohort_young")
employment_terms <- c(cognitive_terms, "round7")

fit <- function(data, outcome, predictor, terms, iv = FALSE) {
  formula <- reformulate(c(predictor, terms), outcome)
  data <- drop_na(data, all_of(c(all.vars(formula), if (iv) "E_is")))
  if (iv) {
    rhs <- paste(terms, collapse = " + ")
    formula <- as.formula(paste(outcome, "~ IMTI +", rhs, "| E_is +", rhs))
    model <- AER::ivreg(formula, data = data)
  } else {
    model <- lm(formula, data = data)
  }
  stopifnot(nobs(model) == nrow(data))
  coefficients <- coef(summary(model))
  stopifnot(predictor %in% rownames(coefficients))
  c(beta = coefficients[predictor, 1], se = coefficients[predictor, 2],
    p = coefficients[predictor, 4], n = nrow(data),
    r2 = if (!iv) summary(model)$r.squared else NA_real_)
}

row <- function(label, cells) {
  paste(paste(c(label, cells), collapse = " & "), strrep(intToUtf8(92), 2))
}
fmt <- function(x) sprintf("%.3f", x)
model_rows <- function(label, estimates) {
  stars <- case_when(
    estimates["p", ] < .01 ~ "$^{***}$",
    estimates["p", ] < .05 ~ "$^{**}$",
    estimates["p", ] < .10 ~ "$^{*}$",
    TRUE ~ ""
  )
  c(row(label, paste0(fmt(estimates["beta", ]), stars)),
    row("", paste0("(", fmt(estimates["se", ]), ")")))
}
write_table <- function(name, caption, label, headers, body, notes) {
  file <- file.path("output/tables", paste0(name, ".tex"))
  writeLines(c(
    "% Generated by code/16_pooled_supplementary_results.R",
    "\\begin{table}[!htbp]\\centering", paste0("\\caption{", caption, "}"),
    paste0("\\label{", label, "}"), "\\begin{threeparttable}\\small",
    paste0("\\begin{tabular}{l", strrep("r", length(headers)), "}\\toprule"),
    row("", headers), "\\midrule", body, "\\bottomrule\\end{tabular}",
    "\\begin{tablenotes}\\footnotesize", paste("\\item", notes),
    "\\item Conventional SEs in parentheses. Stars indicate",
    "$^{***}p<0.01$, $^{**}p<0.05$, and $^{*}p<0.10$.",
    "\\end{tablenotes}\\end{threeparttable}\\end{table}"
  ), file)
  mirror_output(file, "tables")
}

non_addis <- filter(cognitive, !addis, raw_lang_r4 != 0) |>
  mutate(std_lang = as.numeric(scale(raw_lang_r4)))
channels <- cbind(
  fit(non_addis, "std_lang", "inst", cognitive_terms),
  fit(filter(non_addis, region != "Amhara"), "std_lang", "inst", cognitive_terms)
)

headers <- c("Maths z-score", "Language z-score", "Salary employed", "Wage employed")
outcomes <- c("std_maths", "std_lang", "salary_employ", "wage_employ")
run_addis <- function(iv) {
  map(seq_along(outcomes), function(i) {
    data <- if (i <= 2) filter(cognitive, addis) else filter(sample, region == "Addis Ababa")
    terms <- if (i <= 2) cognitive_terms else employment_terms
    fit(data, outcomes[i], if (iv) "IMTI" else "E_is", terms, iv)
  }) |> do.call(what = cbind, args = _)
}
addis_rf <- run_addis(FALSE)
addis_iv <- run_addis(TRUE)
stopifnot(identical(addis_rf["n", ], addis_iv["n", ]))

regional <- map(seq_along(outcomes), function(i) {
  data <- if (i <= 2) cognitive else sample
  data <- filter(data, region %in% c("Tigray", "Oromia")) |>
    mutate(tigray = as.integer(region == "Tigray"))
  if (i == 2) {
    data <- filter(data, chlang == testlang_lang,
                   chlang == if_else(tigray == 1, "Tigrigna", "Afaan Oromo"))
  }
  terms <- if (i <= 2) cognitive_terms else employment_terms
  fit(data, outcomes[i], "tigray", c(terms, "IMTI"))
}) |> do.call(what = cbind, args = _)

