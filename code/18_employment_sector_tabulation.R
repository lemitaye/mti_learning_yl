# Salary and wage jobs by employer type in the pooled summary sample.
library(tidyverse)
source("code/helpers/fixed_employment_sample.R")
source("code/helpers/export_paths.R")

sample <- fixed_employment_sample()
stopifnot(all(sample$salary_employ + sample$wage_employ <= 1),
          all(sample$private_employ + sample$public_employ <= 1, na.rm = TRUE))
groups <- c("Non-Addis", "Addis")
jobs <- c("Salary", "Wage")
sectors <- c("Private", "Public", "Other or unknown")
sample <- sample |>
  mutate(
    group = if_else(region == "Addis Ababa", "Addis", "Non-Addis"),
    job = case_when(salary_employ == 1 ~ "Salary", wage_employ == 1 ~ "Wage"),
    sector = case_when(private_employ == 1 ~ "Private", public_employ == 1 ~ "Public",
                       TRUE ~ "Other or unknown")
  )
counts <- sample |>
  filter(!is.na(job)) |>
  count(group, job, sector, name = "count") |>
  complete(group = groups, job = jobs, sector = sectors, fill = list(count = 0L)) |>
  left_join(count(sample, group, name = "total"), by = "group") |>
  mutate(share = count / total)

row <- function(cells) paste(paste(cells, collapse = " & "), strrep(intToUtf8(92), 2))
body <- map(jobs, function(job_name) {
  map_chr(sectors, function(sector_name) {
    cells <- counts |>
      filter(job == job_name, sector == sector_name) |>
      slice(match(groups, group))
    row(c(paste(job_name, tolower(sector_name), sep = " -- "),
          cells$count[1], sprintf("%.3f", cells$share[1]),
          cells$count[2], sprintf("%.3f", cells$share[2])))
  })
})

file <- "output/tables/table_employment_sector.tex"
dir.create(dirname(file), recursive = TRUE, showWarnings = FALSE)
writeLines(c(
  "% Generated by code/18_employment_sector_tabulation.R",
  "\\begin{table}[!htbp]\\centering",
  "\\caption{Salary and wage employment by employer type}",
  "\\label{tab:employment-sector}",
  "\\linespread{1}\\selectfont",
  "\\begin{threeparttable}\\footnotesize",
  "\\begin{tabular}{lrrrr}\\toprule",
  row(c("", "\\multicolumn{2}{c}{Non-Addis}", "\\multicolumn{2}{c}{Addis}")),
  "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}",
  row(c("", "Count", "Share", "Count", "Share")), "\\midrule",
  body[[1]], "\\addlinespace", body[[2]], "\\midrule",
  row(c("Sample size", sum(sample$group == groups[1]), "",
        sum(sample$group == groups[2]), "")),
  "\\bottomrule\\end{tabular}\\begin{tablenotes}\\scriptsize",
  "\\item Shares use all participant-round observations in each group in",
  "Table~\\ref{tab:employment-partition}. Only salary and wage jobs are shown.",
  "Employer type refers to the first-ranked R5 or annual main R7 job.",
  "Private covers companies, enterprises, and cooperatives. Public covers",
  "government and public-sector employers. Other or unknown includes all",
  "remaining employer types and missing responses.",
  "\\end{tablenotes}\\end{threeparttable}\\end{table}"
), file)
mirror_output(file, "tables")
print(counts, n = Inf)
