# Fit the pooled employment specification to four job and employer combinations.
library(tidyverse)
source("code/helpers/fixed_employment_sample.R")
source("code/helpers/wild_iv_few_regions.R")
source("code/helpers/export_paths.R")

pooled <- main_results_panels(fixed_employment_sample())$B
outcomes <- c("salary_private", "salary_public", "wage_private", "wage_public")
data <- pooled$data |>
  mutate(
    salary_private = as.integer(salary_employ == 1 & private_employ == 1),
    salary_public = as.integer(salary_employ == 1 & public_employ == 1),
    wage_private = as.integer(wage_employ == 1 & private_employ == 1),
    wage_public = as.integer(wage_employ == 1 & public_employ == 1)
  )
controls <- paste(pooled$terms, collapse = " + ")
results <- map_dfr(c(FALSE, TRUE), function(exclude_amhara) {
  group <- if (exclude_amhara) filter(data, region != "Amhara") else data
  map_dfr(outcomes, function(outcome) {
    sample <- drop_na(group, all_of(outcome))
    fit <- fit_main_results_iv(sample, outcome, pooled$terms)
    wild <- wild_iv_few_regions(sample, outcome, controls, unname(fit$iv[1]))
    bind_cols(
      tibble(
        outcome = outcome, exclude_amhara = exclude_amhara,
        fs_beta = fit$fs[1], fs_se = fit$fs[2], fs_p = fit$fs[4],
        fs_F = unname(fit$fs[3]^2),
        iv_beta = fit$iv[1], iv_se = fit$iv[2], iv_p = fit$iv[4],
        n = nrow(sample), participants = n_distinct(sample$child_id)
      ),
      wild$stats
    )
  })
})

fmt <- function(x, digits = 3) formatC(x, format = "f", digits = digits)
row <- function(label, cells) {
  paste(paste(c(label, cells), collapse = " & "), strrep(intToUtf8(92), 2))
}
estimate <- function(label, beta, se, p) {
  stars <- case_when(
    p < .01 ~ "$^{***}$", p < .05 ~ "$^{**}$", p < .10 ~ "$^{*}$", TRUE ~ ""
  )
  c(row(label, paste0(fmt(beta), stars)), row("", paste0("(", fmt(se), ")")))
}
