# Pooled salary and wage IVs conditional on observed public employment.
library(tidyverse)
source("code/helpers/fixed_employment_sample.R")
source("code/helpers/export_paths.R")

pooled <- main_results_panels(fixed_employment_sample())$B
terms <- c(pooled$terms, "public_employ")
controls <- paste(terms, collapse = " + ")
sample <- pooled$data |>
  drop_na(public_employ) |>
  mutate(mti_public = IMTI * public_employ,
         predicted_public = E_is * public_employ)
outcomes <- c("salary_employ", "wage_employ")

results <- map_dfr(c(FALSE, TRUE), function(exclude_amhara) {
  data <- if (exclude_amhara) filter(sample, region != "Amhara") else sample
  stage_terms <- c(terms, "E_is", "predicted_public")
  stage_f <- map_dbl(c("IMTI", "mti_public"), function(outcome) {
    restricted <- lm(reformulate(terms, outcome), data = data)
    full <- lm(reformulate(stage_terms, outcome), data = data)
    stopifnot(full$rank == length(stage_terms) + 1L)
    anova(restricted, full)[2, "F"]
  })
  map_dfr(outcomes, function(outcome) {
    formula <- as.formula(paste(
      outcome, "~ IMTI + mti_public +", controls,
      "| E_is + predicted_public +", controls
    ))
    model <- AER::ivreg(formula, data = data, na.action = na.fail)
    stopifnot(nobs(model) == nrow(data), all(is.finite(coef(model))))
    coefficients <- coef(summary(model))
    slopes <- c("IMTI", "mti_public")
    public_slope_se <- sqrt(sum(vcov(model)[slopes, slopes]))
    tibble(
      outcome = outcome, exclude_amhara = exclude_amhara,
      mti = coefficients["IMTI", 1], mti_se = coefficients["IMTI", 2],
      interaction = coefficients["mti_public", 1],
      interaction_se = coefficients["mti_public", 2],
      public = coefficients["public_employ", 1],
      public_se = coefficients["public_employ", 2],
      public_slope = sum(coef(model)[slopes]), public_slope_se = public_slope_se,
      fs_mti = stage_f[1], fs_interaction = stage_f[2],
      n = nobs(model), public_n = sum(data$public_employ == 1)
    )
  })
})

fmt <- function(x) sprintf("%.3f", x)
row <- function(label, values) {
  paste(paste(c(label, values), collapse = " & "), strrep(intToUtf8(92), 2))
}
estimate <- function(label, beta, se) {
  c(row(label, fmt(beta)), row("", paste0("(", fmt(se), ")")))
}

